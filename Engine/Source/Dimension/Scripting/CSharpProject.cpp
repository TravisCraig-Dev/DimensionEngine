#include "Dimension/Scripting/CSharpProject.h"
#include "Dimension/Core/Log.h"
#include <fstream>

namespace Dimension::CSharpProject
{
    fs::path ScriptsDirectory(const fs::path& projectDir) { return projectDir / "Scripts"; }
    fs::path ProjectFile(const fs::path& projectDir) { return ScriptsDirectory(projectDir) / "GameScripts.csproj"; }
    fs::path AssemblyPath(const fs::path& projectDir) { return projectDir / ".dimension" / "ScriptAssemblies" / "GameScripts.dll"; }

    void Scaffold(const fs::path& projectDir, const fs::path& managedDir)
    {
        std::error_code ec;
        fs::path dir = ScriptsDirectory(projectDir);
        fs::create_directories(dir, ec);

        // Machine-specific paths live in Directory.Build.props (imported automatically by MSBuild).
        std::ofstream props(dir / "Directory.Build.props");
        props << "<Project>\n"
                 "  <!-- Generated by the Dimension editor; do not edit. -->\n"
                 "  <PropertyGroup>\n"
                 "    <DimensionManagedDir>" << fs::absolute(managedDir).string() << "</DimensionManagedDir>\n"
                 "    <BaseIntermediateOutputPath>$(MSBuildThisFileDirectory)..\\.dimension\\obj\\</BaseIntermediateOutputPath>\n"
                 "  </PropertyGroup>\n"
                 "</Project>\n";

        if (!fs::exists(ProjectFile(projectDir)))
        {
            std::ofstream csproj(ProjectFile(projectDir));
            csproj << "<Project Sdk=\"Microsoft.NET.Sdk\">\n"
                      "  <PropertyGroup>\n"
                      "    <TargetFramework>net10.0</TargetFramework>\n"
                      "    <AssemblyName>GameScripts</AssemblyName>\n"
                      "    <RootNamespace>Game</RootNamespace>\n"
                      "    <ImplicitUsings>enable</ImplicitUsings>\n"
                      "    <Nullable>disable</Nullable>\n"
                      "    <EnableDynamicLoading>true</EnableDynamicLoading>\n"
                      "    <AppendTargetFrameworkToOutputPath>false</AppendTargetFrameworkToOutputPath>\n"
                      "  </PropertyGroup>\n"
                      "  <ItemGroup>\n"
                      "    <Reference Include=\"Dimension.Core\">\n"
                      "      <HintPath>$(DimensionManagedDir)\\Dimension.Core.dll</HintPath>\n"
                      "      <Private>false</Private>\n"
                      "    </Reference>\n"
                      "  </ItemGroup>\n"
                      "</Project>\n";
            Log::Info("Created C# project {}", ProjectFile(projectDir).string());
        }
    }

    bool HasSources(const fs::path& projectDir)
    {
        std::error_code ec;
        fs::path dir = ScriptsDirectory(projectDir);
        if (!fs::exists(dir)) return false;
        for (auto& e : fs::recursive_directory_iterator(dir, ec))
            if (e.path().extension() == ".cs") return true;
        return false;
    }

    fs::file_time_type LatestSourceTime(const fs::path& projectDir)
    {
        auto latest = fs::file_time_type::min();
        std::error_code ec;
        fs::path dir = ScriptsDirectory(projectDir);
        if (!fs::exists(dir)) return latest;
        for (auto it = fs::recursive_directory_iterator(dir, ec); it != fs::recursive_directory_iterator(); it.increment(ec))
        {
            if (ec) break;
            const auto& path = it->path();
            if (it->is_directory() && (path.filename() == "bin" || path.filename() == "obj"))
            {
                it.disable_recursion_pending();
                continue;
            }
            auto ext = path.extension();
            if (ext == ".cs" || ext == ".csproj") latest = std::max(latest, fs::last_write_time(path, ec));
        }
        return latest;
    }

    std::string BuildCommand(const fs::path& projectDir)
    {
        fs::path out = AssemblyPath(projectDir).parent_path();
        // Outer quotes are stripped by cmd /c (used by _popen).
        return "\"dotnet build \"" + ProjectFile(projectDir).string() + "\" -c Debug -o \"" + out.string() +
               "\" --nologo -v q -clp:NoSummary 2>&1\"";
    }
}
